export * from './context'
export * from './types'
export * from './darija-seed-lexicon'
export const CONTENT_SAFETY_ENGINE_VERSION = '0.2.1'
const CONTEXTUAL_PURPOSES = new Set(['dictionary_definition', 'linguistic_analysis', 'academic_quote', 'moderation_report'])
const RULE_CATEGORIES = new Set(['profanity', 'personal_abuse', 'hate_speech', 'threat'])
const CONTENT_SURFACES = new Set(['profile', 'lexicon', 'contribution', 'review', 'comment', 'discussion', 'report', 'private_message', 'admin'])
const CONTENT_PURPOSES = new Set(['general', 'dictionary_definition', 'linguistic_analysis', 'academic_quote', 'moderation_report'])
function phraseMatches(text: string, phrase: string): boolean {
  return (' ' + text + ' ').includes(' ' + normalizeSafetyText(phrase) + ' ')
}
function phraseMatchesWithSeparators(text: string, phrase: string): boolean {
  const tokens = normalizeSafetyText(phrase).split(' ').filter(Boolean)
  if (!tokens.length) return false
  // Permit spaces and common punctuation between letters, but retain token
  // boundaries so short rules do not match inside unrelated words.
  const tokenPattern = tokens
    .map((token) => Array.from(token).join('[\s._*-]*'))
    .join('\\s+')
  return new RegExp('(?:^|\\s)' + tokenPattern + '(?:$|\\s)', 'u').test(text)
}
function ruleMatches(text: string, skeleton: string, rule: SafetyLexiconRule): boolean {
  const normalizedPhrase = normalizeSafetyText(rule.phrase)
  if (!normalizedPhrase) return false
  const normalizedRuleSkeleton = obfuscationSkeleton(rule.phrase)
  return phraseMatches(text, normalizedPhrase) ||
    phraseMatchesWithSeparators(skeleton, normalizedRuleSkeleton)
}
function uniqueSignals(signals: SafetySignal[]): SafetySignal[] {
  const seen = new Set<string>()
  return signals.filter((signal) => {
    const key = signal.code + ':' + (signal.ruleId ?? '')
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })
}
export interface ScanContentInput {
  text: string
  surface: ContentSurface
  /** Must be generated by trusted server-side workflow. */
  context?: TrustedContentContext
  now?: Date
}
export function scanContent(input: ScanContentInput, policy: SafetyPolicy): ContentSafetyResult {
  if (!input || typeof input.text !== 'string') throw new TypeError('input.text must be a string')
  if (!CONTENT_SURFACES.has(input.surface)) throw new TypeError('Unsupported content surface')
  if (input.context && !CONTENT_PURPOSES.has(input.context.purpose)) throw new TypeError('Unsupported trusted content purpose')
  if (input.now && !Number.isFinite(input.now.getTime())) throw new TypeError('input.now must be a valid Date')
  if (!policy || !policy.version.trim()) throw new TypeError('policy.version is required')
  if (!Number.isInteger(policy.maxCharacters) || policy.maxCharacters < 1 ||
      !Number.isInteger(policy.maxRepeatedCharacterRun) || policy.maxRepeatedCharacterRun < 1 ||
      !Number.isInteger(policy.maxUrls) || policy.maxUrls < 0) {
    throw new RangeError('Safety content limits must be non-negative integers; maxCharacters and repeated-run limit must be positive')
  }
  if (!Array.isArray(policy.rules) || policy.rules.length > 5000) throw new RangeError('Safety policy must contain at most 5000 rules')
  const ruleIds = new Set<string>()
  for (const rule of policy.rules) {
    if (!rule.id.trim() || ruleIds.has(rule.id) || !RULE_CATEGORIES.has(rule.category) || !normalizeSafetyText(rule.phrase) || rule.phrase.length > 120 ||
        !Number.isInteger(rule.severity) || rule.severity < 1 || rule.severity > 5) {
      throw new TypeError('Safety rules require unique IDs, non-empty phrases, and severity from 1 to 5')
    }
    ruleIds.add(rule.id)
  }
  if (!Number.isFinite(policy.reviewThreshold) || !Number.isFinite(policy.blockThreshold) ||
      policy.reviewThreshold < 0 || policy.reviewThreshold > 100 || policy.blockThreshold < 0 || policy.blockThreshold > 100 ||
      policy.reviewThreshold > policy.blockThreshold) throw new RangeError('Safety thresholds must satisfy 0 <= reviewThreshold <= blockThreshold <= 100')
  const original = input.text
  if (Array.from(original).length > policy.maxCharacters) {
    return makeResult('block', 100, [{
      code: 'content_length_limit_exceeded', category: 'spam', severity: 2, confidence: 'high',
    }], true, policy, input.now)
  }
  const normalized = normalizeSafetyText(original)
  const skeleton = obfuscationSkeleton(original)
  const context = input.context ?? { purpose: 'general' as const }
  const signals: SafetySignal[] = []
  let score = 0
  if (!original.trim()) return makeResult('allow', 0, [], false, policy, input.now, analyzeDarijaContext({ text: original }))
  for (const rule of policy.rules) {
    if (!ruleMatches(normalized, skeleton, rule)) continue
    const targeted = rule.category === 'threat' ? true
      : rule.category === 'hate_speech' ? Boolean(context.targetedAtGroup || context.explicitIncitement)
      : rule.category === 'personal_abuse' ? Boolean(context.targetedAtPerson) : false
    const contextual = CONTEXTUAL_PURPOSES.has(context.purpose) && Boolean(context.quotedForEvidence || context.purpose !== 'general')
    const weight = rule.severity * (rule.category === 'threat' ? 18 : rule.category === 'hate_speech' ? 15 : 10)
    score += rule.category === 'profanity' && contextual && !targeted ? Math.min(8, weight) : weight
    signals.push({ code: targeted ? rule.category + '_targeted' : rule.category + '_term_match', category: rule.category, severity: rule.severity, ruleId: rule.id, confidence: 'medium' })
  }
  const contextAssessment = analyzeDarijaContext({ text: original, matchedCategories: signals.map((signal) => signal.category) })
  if (longestRepeatedCharacterRun(original) > policy.maxRepeatedCharacterRun) {
    score += 8
    signals.push({ code: 'character_flooding', category: 'spam', severity: 2, confidence: 'high' })
  }
  const urls = countUrls(original)
  if (urls > policy.maxUrls) {
    score += Math.min(20, (urls - policy.maxUrls) * 5)
    signals.push({ code: 'excessive_urls', category: 'spam', severity: 3, confidence: 'high' })
  }
  const separatedLetters = /(?:\p{L}[\s.*_-]+){2,}\p{L}/u.test(original)
  if (separatedLetters && signals.some((signal) => signal.category !== 'spam')) {
    score += 6
    signals.push({ code: 'possible_obfuscation', category: 'obfuscation', severity: 2, confidence: 'low' })
  }
  const unique = uniqueSignals(signals)
  const hasThreat = unique.some((signal) => signal.category === 'threat')
  const targetedHate = unique.some((signal) => signal.category === 'hate_speech') && Boolean(context.targetedAtGroup || context.explicitIncitement)
  const targetedAbuse = unique.some((signal) => signal.category === 'personal_abuse') && Boolean(context.targetedAtPerson)
  const contextualEvidence = CONTEXTUAL_PURPOSES.has(context.purpose) && Boolean(context.quotedForEvidence)
  const contextualOnlyProfanity = unique.length > 0 && unique.every((signal) => signal.category === 'profanity' || signal.category === 'obfuscation') &&
    CONTEXTUAL_PURPOSES.has(context.purpose) && Boolean(context.quotedForEvidence || context.purpose !== 'general')
  let decision: ContentSafetyResult['decision'] = 'allow'
  let review = false
  if (contextualEvidence && unique.length > 0) {
    decision = 'allow_with_context'; review = true
  } else if (hasThreat || (targetedHate && context.explicitIncitement)) {
    decision = 'urgent_escalation'; review = true; score = Math.max(score, 95)
  } else if (targetedHate || targetedAbuse) {
    decision = 'block'; review = true; score = Math.max(score, policy.blockThreshold)
  } else if (contextualOnlyProfanity) {
    decision = 'allow_with_context'
  } else if (score >= policy.blockThreshold) {
    if (unique.some((signal) => signal.category === 'spam')) { decision = 'block'; review = true }
    else { decision = 'review'; review = true }
  } else if (score >= policy.reviewThreshold || unique.length > 0) {
    decision = 'review'; review = true
  }
  if (contextAssessment.requiresHumanReview && decision === 'allow') { decision = 'review'; review = true }
  return makeResult(decision, Math.min(100, score), unique, review || contextAssessment.requiresHumanReview, policy, input.now, contextAssessment)
}
function makeResult(decision: ContentSafetyResult['decision'], score: number, signals: SafetySignal[], requiresHumanReview: boolean, policy: SafetyPolicy, now?: Date, contextAssessment?: ReturnType<typeof analyzeDarijaContext>): ContentSafetyResult {
  return {
    decision, riskLevel: score >= 85 ? 'critical' : score >= 60 ? 'high' : score >= 25 ? 'medium' : 'low',
    score, signals, ...(contextAssessment ? { contextAssessment } : {}), requiresHumanReview, engineVersion: CONTENT_SAFETY_ENGINE_VERSION,
    policyVersion: policy.version, processedAt: (now ?? new Date()).toISOString(),
  }
}
